#!/usr/bin/env python3
"""Build the bundled CC-CEDICT snapshot. Never reads user data or API results."""
import argparse, collections, gzip, hashlib, json, re
from pathlib import Path

parser=argparse.ArgumentParser()
parser.add_argument('--source',required=True,type=Path)
parser.add_argument('--license',required=True,type=Path)
parser.add_argument('--output',required=True,type=Path)
args=parser.parse_args()
raw=args.source.read_bytes()
text=gzip.decompress(raw).decode('utf-8-sig')
metadata={key:value.strip() for key,value in re.findall(r'^#! ([^=]+)=(.*)$',text,re.M)}
assert metadata.get('license')=='https://creativecommons.org/licenses/by-sa/4.0/'
forward=collections.defaultdict(list)
reverse=collections.defaultdict(list)
count=0
skip=re.compile(r'^(?:CL:|see |variant of |old variant of |archaic variant of |Taiwan pr\.|also pr\.|abbr\.|abbr for |surname |used in |used as )',re.I)
def normalize(value):
    return re.sub(r'\s+',' ',value.strip()).lower().replace('’',"'")
def clean(value):
    value=re.sub(r'\([^)]*\)','',value)
    value=re.sub(r'\[[^]]*\]','',value)
    value=re.sub(r'<[^>]+>','',value)
    value=re.sub(r'^to\s+','',value.strip())
    return re.sub(r'\s+',' ',value).strip(' ;')
def add(target,key,value):
    if value and value not in target[key]:target[key].append(value)
for line in text.splitlines():
    if not line or line.startswith('#'):continue
    match=re.match(r'^(\S+) (\S+) \[.*?\] /(.*)/$',line)
    if not match:continue
    count+=1
    traditional,simplified,body=match.groups()
    for gloss in re.split(r'/|;',body):
        if skip.match(gloss.strip()):continue
        value=clean(gloss)
        if not value or len(value)>140 or not re.search('[A-Za-z]',value):continue
        for key in {traditional,simplified}:
            add(forward,normalize(key),value)
        english=normalize(value).strip('!.?')
        if len(english)<=70 and len(english.split())<=7 and re.fullmatch(r"[a-z0-9][a-z0-9 '\-]*",english):
            add(reverse,english,simplified)
preferred={'hello':['你好','您好'],'hi':['你好'],'i':['我'],'me':['我'],'you':['你','您'],'we':['我们'],'he':['他'],'she':['她'],'it':['它'],'they':['他们'],'thanks':['谢谢'],'thank you':['谢谢'],'good morning':['早上好'],'good night':['晚安'],'input method':['输入法'],'dictionary':['词典','字典'],'test':['测试','测验'],'bank':['银行','岸']}
for key,values in reverse.items():
    priority=preferred.get(key,[])
    values.sort(key=lambda x:(priority.index(x) if x in priority else 100,0 if 2<=len(x)<=4 else 1,len(x),x))
rows=[]
for target,entries in [('en',forward),('zh',reverse)]:
    for key,values in sorted(entries.items()):
        value=' | '.join(values[:4]).replace('\t',' ').replace('\r',' ').replace('\n',' ')
        if key and value:rows.append(target+'\t'+key+'\t'+value+'\n')
payload=gzip.compress(''.join(rows).encode('utf-8'),compresslevel=9,mtime=0)
args.output.mkdir(parents=True,exist_ok=True)
(args.output/'cc-cedict.tsv.gz').write_bytes(payload)
(args.output/'LICENSE-CC-BY-SA-4.0.txt').write_bytes(args.license.read_bytes())
result={'name':'CC-CEDICT','publisher':'MDBG / CC-CEDICT contributors','license':'CC-BY-SA-4.0','sourceUrl':'https://www.mdbg.net/chinese/export/cedict/cedict_1_0_ts_utf-8_mdbg.txt.gz','sourcePage':'https://www.mdbg.net/chinese/dictionary?page=cc-cedict','sourceDate':metadata['date'],'sourceEntries':count,'sourceSha256':hashlib.sha256(raw).hexdigest(),'englishTargetKeys':len(forward),'chineseTargetKeys':len(reverse),'dataSha256':hashlib.sha256(payload).hexdigest(),'dataBytes':len(payload),'format':1,'adaptation':'Normalized exact word/phrase indexes; references and classifier-only definitions omitted; reverse index and limited common-meaning priorities added. No user content or AI results.'}
(args.output/'manifest.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
(args.output/'NOTICE.txt').write_text('CC-CEDICT, published by MDBG and community contributors.\nSource: https://www.mdbg.net/chinese/dictionary?page=cc-cedict\nLicense: Creative Commons Attribution-ShareAlike 4.0 International.\nCEDICT referenced work: Copyright (C) 1997, 1998 Paul Andrew Denisowski.\nYandu adaptation: exact word/phrase indexes and reverse lookup, generated by tools/build-lexicon.py. This adapted dictionary remains under CC-BY-SA-4.0.\nNo user vocabulary, translation history, private configuration or API results are included.\nSource snapshot: '+metadata['date']+'\n',encoding='utf-8')
print(json.dumps(result,ensure_ascii=True))
